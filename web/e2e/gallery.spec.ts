import { readFile } from "node:fs/promises";
import path from "node:path";
import SQLite from "better-sqlite3";
import sharp from "sharp";
import { expect as baseExpect, test } from "@playwright/test";
const expect = baseExpect.configure({ timeout: 30_000 });
import { addConfirmedEntrants } from "./fixtures";

test("admin saves a draft, publishes it to homepage and player profiles, edits and unpublishes", async ({ page, browser }, info) => {
  test.setTimeout(240_000);
  await page.route(/^https:\/\/fonts\.(googleapis|gstatic)\.com\//, route => route.abort());
  await page.goto("/admin/gallery");
  await expect(page).toHaveURL(/\/signin/);
  await page.getByRole("button", { name: "Continue with demo account" }).click();
  await expect(page).toHaveURL(/\/home$/);
  addConfirmedEntrants("OD", ["Gallery Partner"]);
  const db = new SQLite(process.env.DATABASE_PATH!);
  const user = db.prepare("select id from users where email='demo@rubstaopen.local'").get() as { id: string };
  db.prepare("insert into profiles (id,user_id,full_name,date_of_birth,gender,mobile) values ('gallery-demo',?,'Gallery Champion','1990-01-01','male','123')").run(user.id);
  db.prepare("insert into player_card_shares (user_id,token,created_at) values (?,'gallery-shared-card',?)").run(user.id, Date.now());
  db.close();
  const image = await sharp({ create: { width: 1200, height: 900, channels: 3, background: '#365c46' } }).composite([{ input: Buffer.from('<svg width="1200" height="900"><text x="110" y="440" font-size="90" fill="#f3eddc">Tournament photo</text></svg>') }]).jpeg().toBuffer();
  await page.goto("/admin/gallery");
  await page.getByRole("link", { name: "Add photo", exact: true }).click();
  await page.getByLabel("Upload photo", { exact: true }).setInputFiles({ name: "champion.jpg", mimeType: "image/jpeg", buffer: image });
  await page.getByRole("combobox", { name: "Player", exact: true }).selectOption({ label: "Gallery Champion" });
  await page.getByRole("combobox", { name: "Second player (optional, for doubles)", exact: true }).selectOption({ label: "Gallery Partner" });
  await page.getByRole("combobox", { name: "Feature as", exact: true }).selectOption("winner");
  await page.getByRole("combobox", { name: "Event", exact: true }).selectOption("OD");
  await page.getByLabel("Photo title").fill("Open doubles champions");
  await page.getByLabel("Caption (optional)").fill("A memorable final. <script>literal caption</script>");
  await page.screenshot({ path: info.outputPath("admin-gallery-editor.png"), fullPage: true });
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Draft saved");
  const edit = await page.getByRole("link", { name: "Edit photo" }).getAttribute("href");
  const id = edit!.split('/').pop()!;
  const guest = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await guest.route(/^https:\/\/fonts\.(googleapis|gstatic)\.com\//, route => route.abort());
  const visitor = await guest.newPage();
  const base = new URL(page.url()).origin;
  try {
    await visitor.goto(`${base}/gallery`);
    await expect(visitor.getByText("No photos published here yet.", { exact: false })).toBeVisible();
    expect((await guest.request.get(`${base}/api/gallery/${id}/image`)).status()).toBe(404);
    expect((await guest.request.get(`${base}/api/admin/gallery/${id}/image`)).status()).toBe(403);
    await page.goto(edit!);
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole("button", { name: "Save & publish", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("Photo published");
    await visitor.reload();
    await expect(visitor.getByRole("heading", { name: "Open doubles champions" })).toBeVisible();
    await expect(visitor.getByText("Gallery Champion & Gallery Partner")).toBeVisible();
    await expect(visitor.getByText("A memorable final. <script>literal caption</script>")).toBeVisible();
    await expect.poll(() => visitor.locator('article img').evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await visitor.screenshot({ path: info.outputPath("public-gallery-mobile.png"), fullPage: true });
    await visitor.goto(`${base}/players/gallery-shared-card`);
    await expect(visitor.getByRole("region", { name: "Tournament photos" })).toContainText("Open doubles champions");
    await page.goto('/profile');
    await expect(page.getByRole("region", { name: "Tournament photos" })).toContainText("Open doubles champions");
    // Serve the real landing files on the same test origin; its API remains real.
    await visitor.route('**/gallery-home-preview', async route => route.fulfill({ contentType: 'text/html', body: await readFile(path.resolve('../index.html'), 'utf8') }));
    await visitor.route('**/assets/**', async route => {
      const asset = new URL(route.request().url()).pathname;
      const types: Record<string,string> = { '.js':'text/javascript', '.css':'text/css', '.jpg':'image/jpeg', '.png':'image/png', '.svg':'image/svg+xml' };
      await route.fulfill({ contentType: types[path.extname(asset)] ?? 'application/octet-stream', body: await readFile(path.resolve('..' + asset)) });
    });
    await visitor.goto(`${base}/gallery-home-preview`);
    await expect(visitor.locator('#tournament-gallery-photos')).toContainText('Open doubles champions');
    await expect(visitor.locator('#court-loader')).toHaveCount(0);
    await visitor.locator('#winners-gallery').evaluate(element => element.scrollIntoView({ block: 'start' }));
    await expect(visitor.locator('#winners-gallery .section-heading')).toHaveCSS('opacity', '1');
    await expect(visitor.locator('#winners-gallery h3')).toBeVisible();
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await visitor.screenshot({ path: info.outputPath("homepage-gallery-mobile.png") });
    await visitor.setViewportSize({ width: 1280, height: 900 });
    await visitor.locator('#winners-gallery').evaluate(element => element.scrollIntoView({ block: 'start' }));
    await expect(visitor.locator('#winners-gallery .section-heading')).toHaveCSS('opacity', '1');
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await visitor.screenshot({ path: info.outputPath("homepage-gallery-desktop.png") });
    await page.goto(edit!);
    await page.getByLabel('Photo title').fill('Celebrating our champions');
    await page.getByRole('button', { name: 'Save & publish changes' }).click();
    await expect(page.getByRole('status')).toContainText('Photo published');
    await visitor.goto(`${base}/gallery`);
    await expect(visitor.getByRole('heading', { name: 'Celebrating our champions' })).toBeVisible();
    await page.goto(edit!);
    await page.getByRole('button', { name: 'Unpublish & save draft' }).click();
    await expect(page.getByRole('status')).toContainText('Draft saved');
    await visitor.reload();
    await expect(visitor.getByText('Celebrating our champions')).toHaveCount(0);
    expect((await guest.request.get(`${base}/api/gallery/${id}/image`)).status()).toBe(404);
    await visitor.goto(`${base}/players/gallery-shared-card`);
    await expect(visitor.getByRole('region', { name: 'Tournament photos' })).toHaveCount(0);
  } finally { await guest.close(); }
});
