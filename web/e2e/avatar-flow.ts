import { expect, type Page, type TestInfo } from "@playwright/test";
import sharp from "sharp";
import { saveDemoAvatar } from "./fixtures";

export async function checkAvatarFlow(page: Page, testInfo: TestInfo) {
  // A synthetic test image; no person's portrait is sent to a provider.
  const png = await sharp({ create: { width: 1024, height: 1024, channels: 3, background: "#cddd76" } }).png().toBuffer();
  let userId = "";
  let calls = 0;
  let releaseGeneration: () => void = () => {};
  const generationGate = new Promise<void>(resolve => { releaseGeneration = resolve; });
  await page.route("**/api/avatar", async route => {
    if (route.request().method() !== "POST") return route.continue();
    expect(route.request().postDataBuffer()?.toString()).toContain('name="consent"');
    calls += 1;
    if (calls === 1) return route.fulfill({ status: 502, json: { error: "Could not create your avatar. Please try again." } });
    await generationGate;
    const saved = saveDemoAvatar(png);
    userId = saved.userId;
    await route.fulfill({ json: { ok: true, version: saved.version } });
  });
  await page.goto("/home");
  await page.getByRole("link", { name: "Create my avatar" }).click();
  await expect(page).toHaveURL(/\/avatar$/);
  await expect(page.getByRole("heading", { level: 1 })).toContainText("court-side character");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByLabel("Your caption")).toHaveCount(0);
  await expect(page.getByRole("checkbox")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Let Rubsta post it on Instagram" })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("avatar-photo-mobile.png"), fullPage: true });
  const fileChooser = page.waitForEvent("filechooser");
  await page.getByRole("button", { name: "Upload photo" }).click();
  await (await fileChooser).setFiles({ name: "test-portrait.png", mimeType: "image/png", buffer: png });
  await expect(page.getByAltText("Your selected photo")).toBeVisible();
  await expect(page.getByRole("checkbox")).not.toBeChecked();
  await page.getByRole("checkbox").check();
  await page.getByRole("button", { name: "Generate my tennis avatar" }).click();
  await expect(page.locator("#avatar").getByRole("alert")).toContainText("Could not create");
  await page.getByRole("button", { name: "Generate my tennis avatar" }).click();
  await expect(page.locator("#avatar").getByRole("status")).toContainText("A little tennis magic");
  await expect(page.getByRole("button", { name: "Change photo" })).toBeHidden();
  await page.screenshot({ path: testInfo.outputPath("avatar-loader-mobile.png"), fullPage: true });
  releaseGeneration();
  await expect(page.getByAltText("Your illustrated tennis avatar")).toBeVisible();
  const revealed = page.getByAltText("Your illustrated tennis avatar").locator("..");
  await expect(revealed).toHaveCSS("opacity", "1");
  await expect(page.getByRole("button", { name: "Photo", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: /(?:Create|Generate) another avatar/ })).toHaveCount(0);
  await page.emulateMedia({ reducedMotion: "reduce" });
  await expect(revealed).toHaveCSS("animation-name", "none");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await expect(page.getByLabel(/Your photo/)).toHaveCount(0);
  const caption = page.getByLabel("Your caption");
  await expect(caption).not.toHaveValue("");
  const suggestions = new Set([await caption.inputValue()]);
  for (let i = 0; i < 5; i += 1) {
    await page.getByRole("button", { name: /Suggest another caption/ }).click();
    const suggested = await caption.inputValue();
    expect(suggestions.has(suggested)).toBe(false);
    suggestions.add(suggested);
  }
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("avatar-caption-mobile.png"), fullPage: true });
  await caption.fill("See you at the baseline.");
  await page.getByRole("button", { name: "Preview my card" }).click();
  await expect(page.getByAltText("Your Instagram card preview")).toBeVisible();
  await expect(caption).toHaveCount(0);
  const permission = page.getByRole("checkbox", { name: /I allow Rubsta Open/ });
  await expect(permission).toBeChecked();
  await permission.uncheck();
  await expect(page.getByRole("button", { name: "Allow Rubsta to post this card" })).toBeDisabled();
  await page.getByRole("button", { name: "Edit caption" }).click();
  await expect(caption).toHaveValue("See you at the baseline.");
  await caption.fill("My next point starts here.");
  await expect(page.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Preview my card" }).click();
  await expect(permission).not.toBeChecked();
  await page.screenshot({ path: testInfo.outputPath("avatar-save-mobile.png"), fullPage: true });
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("link", { name: "Download my card" }).click();
  const download = await downloadPromise;
  await download.saveAs(testInfo.outputPath("avatar-card.png"));
  expect((await sharp((await download.path())!).metadata()).width).toBe(1080);
  expect((await page.request.get(`/api/admin/avatars/${userId}`)).status()).toBe(404);
  const approve = page.getByRole("button", { name: "Allow Rubsta to post this card" });
  await expect(approve).toBeDisabled();
  await page.getByRole("checkbox", { name: /I allow Rubsta Open/ }).check();
  await approve.click();
  await expect(page).toHaveURL(/\/home\?avatar=approved$/);
  await expect(page.getByRole("status")).toContainText("Permission saved");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("avatar-mobile.png"), fullPage: true });

  await page.goto("/avatar");
  await expect(page.getByLabel("Your caption")).not.toHaveValue("My next point starts here.");
  await page.getByText("Avatar options", { exact: true }).click();
  await expect(page.getByRole("button", { name: "Withdraw Instagram permission" })).toBeVisible();
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto("/admin/avatars");
  const approved = page.getByRole("article", { name: "Demo Player" });
  await expect(approved).toBeVisible();
  const adminDownload = approved.getByRole("link", { name: "Download approved card" });
  await expect(adminDownload).toHaveCSS("color", "rgb(255, 251, 237)");
  const adminDownloadPromise = page.waitForEvent("download");
  await adminDownload.click();
  expect((await adminDownloadPromise).suggestedFilename()).toBe("rubsta-instagram-card.png");
  const response = await page.request.get(`/api/admin/avatars/${userId}?download=1`);
  expect(response.status()).toBe(200);
  expect((await sharp(await response.body()).metadata()).height).toBe(1350);
  await page.screenshot({ path: testInfo.outputPath("avatar-admin.png"), fullPage: true });
  await page.goto("/avatar");
  await page.getByText("Avatar options", { exact: true }).click();
  await page.getByRole("button", { name: "Withdraw Instagram permission" }).click();
  await expect(page.getByRole("status")).toContainText("Permission removed");
  expect((await page.request.get(`/api/admin/avatars/${userId}`)).status()).toBe(404);
  expect((await page.request.get("/api/avatar")).status()).toBe(200);
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Delete saved avatar" }).click();
  await expect(page.getByAltText("Your illustrated tennis avatar")).toHaveCount(0);
  expect((await page.request.get("/api/avatar")).status()).toBe(404);
}
